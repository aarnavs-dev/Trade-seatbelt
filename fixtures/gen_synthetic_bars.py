"""Generates fixtures/synthetic_bars/bars_5m.json: SYNTHETIC 5-minute bars for two sessions, from a seeded integer random
walk. They are NOT market data and resemble no real day. Same file format as the replay cache (marketdata/replay.py).
Run: .venv/bin/python fixtures/gen_synthetic_bars.py"""

import random
from datetime import date
from pathlib import Path

import orjson

from marketdata.calendar import session_ms

SEED = 20260930
DAYS = (date(2026, 9, 29), date(2026, 9, 30))   # previous session, then the replayed session
START = {"AAPL": 19000, "MSFT": 42000, "NVDA": 12000, "TSLA": 25000, "SPY": 55000}   # cents
WIDTH = 300_000


def build():
    rng = random.Random(SEED)
    bars = []
    for sym, px in START.items():
        close = px
        for d in DAYS:
            o_ms, c_ms = session_ms(d)
            drift = rng.choice((-4, 0, 6, 12))                  # bps per bar for this symbol-day
            for t0 in range(o_ms, c_ms, WIDTH):
                o = close
                step = drift + rng.randint(-22, 22) + (rng.choice((-1, 1)) * rng.randint(30, 60) if rng.random() < 0.05 else 0)
                close = max(100, o * (10_000 + step) // 10_000)
                h = max(o, close) + o * rng.randint(0, 6) // 10_000
                l = min(o, close) - o * rng.randint(0, 6) // 10_000
                bars.append([sym, t0 + WIDTH, o, h, l, close, rng.randint(1_000, 90_000)])
    bars.sort(key=lambda b: (b[1], b[0]))
    meta = {"provider": "synthetic", "symbols": sorted(START), "interval": "5m", "start": DAYS[0].isoformat(),
            "end": DAYS[1].isoformat(), "timezone": "UTC", "retrieved_at": "2026-10-11T00:00:00Z",
            "notes": ["SYNTHETIC FIXTURE: generated by fixtures/gen_synthetic_bars.py (seeded integer random walk), not market data"]}
    return {"version": 1, "meta": meta, "bars": bars}


if __name__ == "__main__":
    out = Path(__file__).parent / "synthetic_bars" / "bars_5m.json"
    out.write_bytes(orjson.dumps(build(), option=orjson.OPT_SORT_KEYS) + b"\n")
    print(f"wrote {out} ({out.stat().st_size} bytes)")
