def test_the_state_hash_of_a_v2_log_covers_the_records(tmp_path):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS))
    a = audit(p, RULES)
    assert a.book.rules_records and a.book.recorded_rules_hash == rules_hash(RULES)
    _, gate = run(run_gate(tmp_path / "again.log", ORDERS))     # same orders, same deterministic clock: byte-identical
    assert (tmp_path / "again.log").read_bytes() == p.read_bytes() and gate.book.state_hash() == a.book.state_hash()


# ---- the record is chained -------------------------------------------------------------------------------------------

def forge(p, **changes):
    rows = p.read_bytes().splitlines(keepends=True)
    d = json.loads(rows[0])
    d.update(changes)
    return rows, d


@pytest.mark.parametrize("field,value", [("rules_hash", "0" * 64), ("ts", 5), ("log_version", 2 + 1), ("type", "OTHER")])
def test_every_field_of_the_record_is_covered_by_the_chain(tmp_path, field, value):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS))
    rows, d = forge(p, **{field: value})
    p.write_bytes(orjson.dumps(d, option=orjson.OPT_SORT_KEYS) + b"\n" + b"".join(rows[1:]))
    with pytest.raises(ChainError) as e:
        list(scan(p))
    assert e.value.seq == 1


def test_a_forged_record_with_a_recomputed_hash_is_caught_at_the_next_line(tmp_path):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS))
    rows, d = forge(p, rules_hash="f" * 64)
    d["hash"] = event_hash(d["prev_hash"], {k: v for k, v in d.items() if k not in ("hash", "prev_hash")})
    p.write_bytes(orjson.dumps(d, option=orjson.OPT_SORT_KEYS) + b"\n" + b"".join(rows[1:]))
    with pytest.raises(ChainError) as e:
        list(scan(p))
    assert e.value.seq == 2 and "prev_hash" in e.value.reason


def test_dropping_the_record_is_caught_and_a_gate_refuses_to_start_on_it(tmp_path):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS))
    p.write_bytes(b"".join(p.read_bytes().splitlines(keepends=True)[1:]))
    with pytest.raises(ChainError) as e:
        list(scan(p))
    assert e.value.seq == 1
    with pytest.raises(ChainError):
        run(run_gate(p, ORDERS))


def test_a_v2_record_in_the_wrong_place_still_has_to_chain(tmp_path):
    """A record copied from another log (valid on its own, wrong prev_hash here) is rejected like any splice."""
    a, b = tmp_path / "a.log", tmp_path / "b.log"
    run(run_gate(a, ORDERS))
    run(run_gate(b, ORDERS[:2]))
    rec = a.read_bytes().splitlines(keepends=True)[0]
    rows = b.read_bytes().splitlines(keepends=True)
    b.write_bytes(b"".join(rows[:2] + [rec]))
    with pytest.raises(ChainError):
        list(scan(b))
