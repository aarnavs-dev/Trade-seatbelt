"""Invariant 21: a log records which rules the gate ran under, inside the hash chain, and the auditor reports drift.

The gate loads its rules once per process (there is no live reload), so it appends one RULES control record at every
start whose rules hash differs from the last one in the log. v1 logs (no record) must keep verifying exactly as before."""

import json
import shutil
from pathlib import Path

import orjson
import pytest
import yaml

from auditor.replay import audit
from auditor.report import build_report, to_markdown
from core.canon import event_hash
from core.logio import ChainError, scan, scan_records
from core.rules import Rules, load_rules, rules_hash
from tests.helpers import RULES, clock_from, line, run, run_gate

ROOT = Path(__file__).resolve().parent.parent
V1_FIXTURE = ROOT / "fixtures" / "recon" / "gate_log.jsonl"   # generated by a pre-record gate and kept as a v1 log
ORDERS = [line(f"R{i}", "BUY" if i % 2 else "SELL", "AAPL", 5, 19000) for i in range(1, 7)]


def with_rules(**changes) -> Rules:
    return RULES.model_copy(update=changes)


# ---- the hash ---------------------------------------------------------------------------------------------------------

def test_rules_hash_is_of_the_parsed_rules_not_the_file_bytes(tmp_path):
    text = (ROOT / "rules.yaml").read_text()
    reformatted = tmp_path / "r.yaml"
    d = yaml.safe_load(text)
    reformatted.write_text("# a comment\n" + yaml.safe_dump(d, sort_keys=False, default_flow_style=False) + "\n\n")
    assert reformatted.read_bytes() != (ROOT / "rules.yaml").read_bytes()
    assert rules_hash(load_rules(reformatted)) == rules_hash(RULES)


@pytest.mark.parametrize("change", [
    dict(max_position_per_symbol=99), dict(max_daily_loss=4999), dict(price_band_pct=4), dict(max_orders_per_minute=599),
    dict(kill_switch=True), dict(fees=RULES.fees.model_copy(update={"per_share_minor": 2})),
    dict(loss_streak_cooldown=RULES.loss_streak_cooldown.model_copy(update={"losses": 4})),
    dict(symbols={**RULES.symbols, "NVDA": RULES.symbols["AAPL"]}),
    dict(symbols={**RULES.symbols, "AAPL": RULES.symbols["AAPL"].model_copy(update={"reference_price": 19001})}),
])
def test_every_effective_rule_changes_the_hash(change):
    assert rules_hash(with_rules(**change)) != rules_hash(RULES)


# ---- the gate writes it -----------------------------------------------------------------------------------------------

def test_a_new_log_starts_with_a_rules_record_inside_the_chain(tmp_path):
    p = tmp_path / "g.log"
    _, gate = run(run_gate(p, ORDERS))
    recs = list(scan_records(p))
    first = recs[0]
    assert first.type == "RULES" and first.seq == 1 and first.log_version == 2 and first.rules_hash == rules_hash(RULES)
    assert first.prev_hash == "0" * 64 and recs[1].prev_hash == first.hash  # the first order chains off the record
    assert [e.seq for e in scan(p)] == list(range(2, 8))
    assert gate.rules_record == first


def test_restart_with_the_same_rules_writes_no_second_record(tmp_path):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS[:3]))
    run(run_gate(p, ORDERS[3:]))
    assert sum(1 for r in scan_records(p) if hasattr(r, "rules_hash")) == 1
    assert audit(p, RULES).findings == []


def test_restart_with_changed_rules_appends_a_second_record_and_pins_each_segment(tmp_path):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS[:3]))
    tighter = with_rules(max_position_per_symbol=5)
    out, g2 = run(run_gate(p, ORDERS[3:], rules=tighter))
    recs = [r for r in scan_records(p) if hasattr(r, "rules_hash")]
    assert [(r.seq, r.rules_hash) for r in recs] == [(1, rules_hash(RULES)), (5, rules_hash(tighter))]
    assert g2.rules_record.seq == 5                       # 1 record + 3 orders, then the new record
    assert [o["seq"] for o in out] == [6, 7, 8]           # and the next orders follow it
    # one rules file cannot match both segments, and the auditor says so instead of hiding it
    a = audit(p, tighter)
    mismatches = [f for f in a.findings if f["kind"] == "RULES_MISMATCH"]
    assert [f["seq"] for f in mismatches] == [1]
    assert build_report(a, p)["rules_record"]["status"] == "MISMATCH"


def test_a_gate_that_cannot_write_its_record_does_not_start(tmp_path):
    p = tmp_path / "no_such_dir" / "g.log"
    with pytest.raises(OSError):
        run(run_gate(p, ORDERS))


def test_record_rules_false_writes_a_v1_log(tmp_path):
    p = tmp_path / "g.log"
    run(run_gate(p, ORDERS, record_rules=False))
    assert [r.seq for r in scan_records(p)] == list(range(1, 7)) and not any(hasattr(r, "rules_hash") for r in scan_records(p))


def test_the_record_costs_no_order_state(tmp_path):
    """A record moves the chain head but is invisible to everything an order can see: counts, positions, P&L, the
    order window, the dedupe map. Same orders with and without a record give identical order-level results."""
    a1, a2 = tmp_path / "v1.log", tmp_path / "v2.log"
    ts = [1_000_000_000_000 + i * 1_000_000 for i in range(6)]       # the same ts for every order in both logs
    it = iter(ts)
    run(run_gate(a1, ORDERS, record_rules=False, clock=lambda: next(it)))
    run(run_gate(a2, ORDERS, record_rules=True, clock=clock_from(ts)))
    r1, r2 = audit(a1, RULES), audit(a2, RULES)
    assert (r1.events, r1.accepted, dict(r1.rejects)) == (r2.events, r2.accepted, dict(r2.rejects)) == (6, 6, {})
    b1, b2 = r1.book, r2.book
    assert b1.ledger.snapshot() == b2.ledger.snapshot() and list(b1.order_times) == list(b2.order_times)
    assert set(b1.seen) == set(b2.seen)


